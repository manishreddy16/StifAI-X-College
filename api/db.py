def utcnow() -> datetime:
    return datetime.now(timezone.utc).replace(microsecond=0)


def iso(dt: datetime) -> str:
    return dt.astimezone(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


def db_timestamp(dt: datetime) -> datetime:
    """Return a UTC timestamp parameter at the application's existing second precision."""
    return dt.astimezone(timezone.utc).replace(microsecond=0)


def parse_iso(value: str) -> datetime:
    return datetime.strptime(value, "%Y-%m-%dT%H:%M:%SZ").replace(tzinfo=timezone.utc)


def db_path() -> str:
    configured = (os.getenv("STIF_DB_PATH") or "").strip()
    return configured or str(ROOT / "data" / "stif_campus.db")


def database_backend() -> str:
    """Select PostgreSQL only when explicitly configured; SQLite remains the default."""
    return "postgres" if (os.getenv("STIF_DATABASE_URL") or "").strip() else "sqlite"


def database_description() -> str:
    """Safe operator-facing target description; never return a database URL."""
    return "PostgreSQL (STIF_DATABASE_URL)" if database_backend() == "postgres" else f"SQLite ({db_path()})"


class DatabaseRow:
    """Backend-neutral row supporting the existing name and positional access patterns."""

    __slots__ = ("_columns", "_values", "_positions")

    def __init__(self, columns: Sequence[str], values: Sequence[Any]):
        self._columns = tuple(columns)
        self._values = tuple(iso(value) if isinstance(value, datetime) else value for value in values)
        self._positions = {name: index for index, name in enumerate(self._columns)}

    def __getitem__(self, key: str | int) -> Any:
        if isinstance(key, str):
            key = self._positions[key]
        return self._values[key]

    def __len__(self) -> int:
        return len(self._values)

    def keys(self) -> tuple[str, ...]:
        return self._columns


class Result(Protocol):
    """Read-only operations the service layer uses from a query result."""

    @property
    def rowcount(self) -> int: ...
    def fetchone(self) -> DatabaseRow | None: ...
    def fetchall(self) -> list[DatabaseRow]: ...
    def __iter__(self): ...


class DatabaseResult:
    """SQLite result adapter; services depend on the ``Result`` protocol instead."""

    def __init__(self, cursor: Any):
        self._cursor = cursor
        self._columns = tuple(column.name if hasattr(column, "name") else column[0]
                              for column in cursor.description or ())

    @property
    def rowcount(self) -> int:
        return self._cursor.rowcount

    def _row(self, raw: Sequence[Any] | Mapping[str, Any] | None) -> DatabaseRow | None:
        if raw is None:
            return None
        values = tuple(raw[name] for name in self._columns) if isinstance(raw, Mapping) else tuple(raw)
        return DatabaseRow(self._columns, values)

    def fetchone(self) -> DatabaseRow | None:
        return self._row(self._cursor.fetchone())

    def fetchall(self) -> list[DatabaseRow]:
        return [self._row(row) for row in self._cursor.fetchall()]

    def __iter__(self):
        for row in self._cursor:
            yield self._row(row)


class Connection(Protocol):
    """Operations used by services; future database drivers implement this boundary."""

    def execute(self, sql: str, parameters: Sequence[Any] = ()) -> Result: ...
    def insert_id(self, sql: str, parameters: Sequence[Any] = ()) -> int: ...
    def begin(self, *, immediate: bool = False) -> None: ...
    def lock_key(self, key: str) -> None: ...
    def commit(self) -> None: ...
    def rollback(self) -> None: ...
    def close(self) -> None: ...


class SQLiteConnection:
    """SQLite-only adapter. Driver details stay inside this module."""

    def __init__(self, raw: sqlite3.Connection):
        self._raw = raw

    @staticmethod
    def _parameters(parameters: Sequence[Any]) -> tuple[Any, ...]:
        return tuple(iso(value) if isinstance(value, datetime) else value for value in parameters)

    @staticmethod
    def _integrity_error(exc: sqlite3.IntegrityError):
        raise DatabaseIntegrityError("Database constraint violation.") from None

    def execute(self, sql: str, parameters: Sequence[Any] = ()) -> DatabaseResult:
        try:
            return DatabaseResult(self._raw.execute(sql, self._parameters(parameters)))
        except sqlite3.IntegrityError as exc:
            self._integrity_error(exc)

    def insert_id(self, sql: str, parameters: Sequence[Any] = ()) -> int:
        try:
            cursor = self._raw.execute(sql, self._parameters(parameters))
        except sqlite3.IntegrityError as exc:
            self._integrity_error(exc)
        if cursor.lastrowid is None:
            raise RuntimeError("The insert did not produce a generated ID.")
        return int(cursor.lastrowid)

    def begin(self, *, immediate: bool = False) -> None:
        self._raw.execute("BEGIN IMMEDIATE" if immediate else "BEGIN")

    def lock_key(self, key: str) -> None:
        # BEGIN IMMEDIATE already serializes SQLite writers for this connection.
        return None

    def commit(self) -> None:
        self._raw.execute("COMMIT")

    def rollback(self) -> None:
        self._raw.execute("ROLLBACK")

    def close(self) -> None:
        self._raw.close()


class DatabaseIntegrityError(Exception):
    """Backend-neutral integrity/constraint violation."""


IntegrityError = DatabaseIntegrityError


class DatabaseConfigurationError(RuntimeError):
    """Invalid explicitly selected database configuration."""


class DatabaseUnavailable(RuntimeError):
    """Selected database could not be reached or its driver is unavailable."""


def _translate_qmark_sql(sql: str) -> str:
    """Translate service-layer qmark placeholders without touching SQL literals/comments."""
    out: list[str] = []
    i = 0
    state = "normal"
    block_depth = 0
    dollar_tag: str | None = None
    while i < len(sql):
        if state == "normal":
            if sql.startswith("--", i):
                out.append("--"); i += 2; state = "line_comment"; continue
            if sql.startswith("/*", i):
                out.append("/*"); i += 2; state = "block_comment"; block_depth = 1; continue
            if sql[i] == "'":
                out.append(sql[i]); i += 1; state = "single_quote"; continue
            if sql[i] == '"':
                out.append(sql[i]); i += 1; state = "double_quote"; continue
            if sql[i] == "$":
                match = re.match(r"\$[A-Za-z_][A-Za-z0-9_]*\$|\$\$", sql[i:])
                if match:
                    dollar_tag = match.group(0)
                    out.append(dollar_tag); i += len(dollar_tag); state = "dollar_quote"; continue
            if sql[i] == "?":
                out.append("%s"); i += 1; continue
            out.append(sql[i]); i += 1; continue
        if state == "single_quote":
            if sql.startswith("''", i):
                out.append("''"); i += 2; continue
            out.append(sql[i])
            if sql[i] == "'": state = "normal"
            i += 1; continue
        if state == "double_quote":
            if sql.startswith('""', i):
                out.append('""'); i += 2; continue
            out.append(sql[i])
            if sql[i] == '"': state = "normal"
            i += 1; continue
        if state == "line_comment":
            out.append(sql[i])
            if sql[i] in "\r\n": state = "normal"
            i += 1; continue
        if state == "block_comment":
            if sql.startswith("/*", i):
                out.append("/*"); i += 2; block_depth += 1; continue
            if sql.startswith("*/", i):
                out.append("*/"); i += 2; block_depth -= 1
                if block_depth == 0: state = "normal"
                continue
            out.append(sql[i]); i += 1; continue
        if state == "dollar_quote":
            if dollar_tag and sql.startswith(dollar_tag, i):
                out.append(dollar_tag); i += len(dollar_tag); state = "normal"; dollar_tag = None; continue
            out.append(sql[i]); i += 1
    return "".join(out)


def _load_psycopg():
    try:
        import psycopg
        from psycopg.rows import tuple_row
    except ImportError:
        raise DatabaseUnavailable("PostgreSQL is selected but the Psycopg driver is not installed.") from None
    return psycopg, tuple_row


class PostgreSQLConnection:
    """Psycopg adapter implementing the service connection protocol."""

    def __init__(self, raw: Any, integrity_error_type: type[Exception]):
        self._raw = raw
        self._integrity_error_type = integrity_error_type

    def _execute(self, sql: str, parameters: Sequence[Any] = ()) -> Any:
        try:
            return self._raw.execute(_translate_qmark_sql(sql), tuple(parameters))
        except self._integrity_error_type:
            raise DatabaseIntegrityError("Database constraint violation.") from None

    def execute(self, sql: str, parameters: Sequence[Any] = ()) -> DatabaseResult:
        return DatabaseResult(self._execute(sql, parameters))

    def insert_id(self, sql: str, parameters: Sequence[Any] = ()) -> int:
        statement = sql.rstrip().removesuffix(";") + " RETURNING id"
        row = self._execute(statement, parameters).fetchone()
        if row is None:
            raise RuntimeError("The insert did not produce a generated ID.")
        return int(row["id"] if isinstance(row, Mapping) else row[0])

    def begin(self, *, immediate: bool = False) -> None:
        # PostgreSQL has no BEGIN IMMEDIATE. Enquiry serialization uses lock_key().
        self.execute("BEGIN")

    def lock_key(self, key: str) -> None:
        value = int.from_bytes(hashlib.sha256(key.encode("utf-8")).digest()[:8], "big", signed=True)
        self.execute("SELECT pg_advisory_xact_lock(?)", (value,))

    def commit(self) -> None:
        self.execute("COMMIT")

    def rollback(self) -> None:
        self.execute("ROLLBACK")

    def close(self) -> None:
        self._raw.close()


def _postgres_url() -> str:
    value = (os.getenv("STIF_DATABASE_URL") or "").strip()
    try:
        parsed = urlsplit(value)
        # Accessing ``port`` validates malformed/non-numeric ports without echoing the URL.
        _ = parsed.port
    except ValueError:
        raise DatabaseConfigurationError("STIF_DATABASE_URL must be a valid PostgreSQL connection URL.") from None
    if parsed.scheme not in {"postgres", "postgresql"} or not parsed.hostname or not parsed.path.strip("/"):
        raise DatabaseConfigurationError("STIF_DATABASE_URL must be a valid PostgreSQL connection URL.")
    return value


def _connect_postgres() -> PostgreSQLConnection:
    url = _postgres_url()
    psycopg, tuple_row = _load_psycopg()
    try:
        raw = psycopg.connect(url, autocommit=True, row_factory=tuple_row, connect_timeout=10)
    except Exception:
        # Driver errors may include connection details; return a safe configuration-neutral message.
        raise DatabaseUnavailable("PostgreSQL connection failed; verify STIF_DATABASE_URL and database availability.") from None
    return PostgreSQLConnection(raw, psycopg.IntegrityError)


def connect(path: str | None = None) -> Connection:
    """Open PostgreSQL when explicitly configured, otherwise the existing SQLite file.

    Passing a path explicitly always selects SQLite, which keeps tests safely isolated.
    """
    if path is None and database_backend() == "postgres":
        return _connect_postgres()
    # check_same_thread=False: FastAPI may run a request's dependency and handler on different
    # worker threads; each request owns its connection and uses it sequentially.
    raw = sqlite3.connect(path or db_path(), timeout=15, isolation_level=None, check_same_thread=False)
    raw.row_factory = sqlite3.Row
    raw.execute("PRAGMA foreign_keys = ON")
    return SQLiteConnection(raw)


def _init_postgres(conn: PostgreSQLConnection) -> list[int]:
    applied: list[int] = []
    with transaction(conn, immediate=True):
        # Transaction-scoped lock covers table bootstrap and every pending migration.
        conn.lock_key("stif-campus-ai:schema-migrations")
        conn.execute(
            "CREATE TABLE IF NOT EXISTS schema_migrations "
            "(version INTEGER PRIMARY KEY, applied_at TIMESTAMPTZ NOT NULL)"
        )
        done = {row["version"] for row in conn.execute("SELECT version FROM schema_migrations")}
        for version, statements in POSTGRES_MIGRATIONS:
            if version in done:
                continue
            for statement in statements:
                conn.execute(statement)
            conn.execute(
                "INSERT INTO schema_migrations (version, applied_at) VALUES (?, ?)",
                (version, db_timestamp(utcnow())),
            )
            applied.append(version)
    return applied


@contextmanager
def transaction(conn: Connection, *, immediate: bool = False):
    conn.begin(immediate=immediate)
    try:
        yield conn
    except BaseException:
        conn.rollback()
        raise
    else:
        conn.commit()


def init_db(path: str | None = None) -> list[int]:
    """Create or upgrade the schema. Safe to call repeatedly. Returns newly applied versions."""
    if path is None and database_backend() == "postgres":
        conn = connect()
        try:
            return _init_postgres(conn)  # type: ignore[arg-type]
        finally:
            conn.close()

    target = path or db_path()
    if target != ":memory:":
        Path(target).parent.mkdir(parents=True, exist_ok=True)
    conn = connect(target)
    applied: list[int] = []
    try:
        if target != ":memory:":
            conn.execute("PRAGMA journal_mode = WAL")
        conn.execute(
            "CREATE TABLE IF NOT EXISTS schema_migrations (version INTEGER PRIMARY KEY, applied_at TEXT NOT NULL)"
        )
        done = {r["version"] for r in conn.execute("SELECT version FROM schema_migrations")}
        for version, statements in MIGRATIONS:
            if version in done:
                continue
            with transaction(conn, immediate=True):
                for statement in statements:
                    conn.execute(statement)
                conn.execute(
                    "INSERT INTO schema_migrations (version, applied_at) VALUES (?, ?)",
                    (version, iso(utcnow())),
                )
            applied.append(version)
    finally:
        conn.close()
    return applied


_init_lock = threading.Lock()
_initialised: set[str] = set()


def _initialization_key() -> str:
    if database_backend() == "postgres":
        url = (os.getenv("STIF_DATABASE_URL") or "").strip()
        return "postgres:" + hashlib.sha256(url.encode("utf-8")).hexdigest()
    return "sqlite:" + db_path()


def ensure_initialized() -> None:
    """Lazy, once-per-process schema check so the API works regardless of startup hooks."""
    target = _initialization_key()
    if target in _initialised:
        return
    with _init_lock:
        if target not in _initialised:
            init_db() if database_backend() == "postgres" else init_db(db_path())
            _initialised.add(target)


@contextmanager
def session():
    ensure_initialized()
    conn = connect()
    try:
        yield conn
    finally:
        conn.close()
